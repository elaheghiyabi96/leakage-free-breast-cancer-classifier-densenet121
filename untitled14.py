import os
import numpy as np
import pandas as pd
import tensorflow as tf

tf.keras.mixed_precision.set_global_policy('mixed_float16')

from sklearn.utils.class_weight import compute_class_weight
from sklearn.metrics import classification_report, confusion_matrix, accuracy_score
from tensorflow.keras.applications import DenseNet121
from tensorflow.keras.layers import GlobalAveragePooling2D, Dense, Dropout, BatchNormalization
from tensorflow.keras.models import Sequential
from tensorflow.keras.optimizers import Adam
from tensorflow.keras.callbacks import EarlyStopping, ReduceLROnPlateau, ModelCheckpoint
from tensorflow.keras.preprocessing.image import ImageDataGenerator

from google.colab import drive
drive.mount('/content/drive')

# =========================
# 1️⃣ بارگذاری تقسیم‌بندی (همون CSV امن)
# =========================
SPLITS_PATH = "/content/drive/MyDrive/breakhis_ib_outputs/splits_patient_level.csv"
splits_df = pd.read_csv(SPLITS_PATH)

train_df = splits_df[splits_df['split'] == 'train'].reset_index(drop=True)
val_df   = splits_df[splits_df['split'] == 'val'].reset_index(drop=True)
test_df  = splits_df[splits_df['split'] == 'test'].reset_index(drop=True)

print(f"📊 Train: {len(train_df)}, Val: {len(val_df)}, Test: {len(test_df)}")

# =========================
# 2️⃣ Class Weights
# =========================
class_weights = compute_class_weight(
    class_weight='balanced',
    classes=np.unique(train_df['label']),
    y=train_df['label']
)
class_weight_dict = dict(enumerate(class_weights))
print(f"📊 Class Weights: {class_weight_dict}")

# =========================
# 3️⃣ Data Generators
# =========================
IMG_SIZE = 224
BATCH_SIZE = 32

train_datagen = ImageDataGenerator(
    rescale=1./255,
    rotation_range=45,
    width_shift_range=0.25,
    height_shift_range=0.25,
    shear_range=0.2,
    zoom_range=0.25,
    horizontal_flip=True,
    vertical_flip=True,
    brightness_range=[0.6, 1.4],
    channel_shift_range=15,
    fill_mode='reflect'
)
val_datagen = ImageDataGenerator(rescale=1./255)

train_generator = train_datagen.flow_from_dataframe(
    train_df, x_col="filename", y_col="label",
    target_size=(IMG_SIZE, IMG_SIZE), batch_size=BATCH_SIZE,
    class_mode="raw", shuffle=True
)
val_generator = val_datagen.flow_from_dataframe(
    val_df, x_col="filename", y_col="label",
    target_size=(IMG_SIZE, IMG_SIZE), batch_size=BATCH_SIZE,
    class_mode="raw", shuffle=False
)
test_generator = val_datagen.flow_from_dataframe(
    test_df, x_col="filename", y_col="label",
    target_size=(IMG_SIZE, IMG_SIZE), batch_size=BATCH_SIZE,
    class_mode="raw", shuffle=False
)

steps_per_epoch = len(train_df) // BATCH_SIZE
validation_steps = len(val_df) // BATCH_SIZE

# =========================
# 4️⃣ ساخت مدل DenseNet121
# =========================
print("\n🧠 Building DenseNet121...")

base_model = DenseNet121(
    weights='imagenet',
    include_top=False,
    input_shape=(IMG_SIZE, IMG_SIZE, 3)
)
base_model.trainable = False

model_densenet121 = Sequential([
    base_model,
    GlobalAveragePooling2D(),
    BatchNormalization(),
    Dense(512, activation='relu'),
    Dropout(0.5),
    Dense(256, activation='relu'),
    Dropout(0.3),
    Dense(1, activation='sigmoid', dtype='float32')
])

model_densenet121.summary()

# =========================
# 5️⃣ Callbacks
# =========================
DRIVE_MODEL_DIR = "/content/drive/MyDrive/breakhis_models"
os.makedirs(DRIVE_MODEL_DIR, exist_ok=True)

callbacks = [
    EarlyStopping(patience=8, restore_best_weights=True, verbose=1),
    ReduceLROnPlateau(factor=0.3, patience=4, min_lr=1e-7, verbose=1),
    ModelCheckpoint(
        os.path.join(DRIVE_MODEL_DIR, 'densenet121_patient_best.keras'),
        save_best_only=True, verbose=1
    )
]

# =========================
# 6️⃣ آموزش (۳ فاز)
# =========================
# Phase 1: Frozen
print("\n🚀 PHASE 1: Frozen")
model_densenet121.compile(optimizer=Adam(1e-3), loss='binary_crossentropy', metrics=['accuracy'])
model_densenet121.fit(
    train_generator, steps_per_epoch=steps_per_epoch, epochs=30,
    validation_data=val_generator, validation_steps=validation_steps,
    class_weight=class_weight_dict, callbacks=callbacks, verbose=1
)

# Phase 2: Fine-Tuning
print("\n🔧 PHASE 2: Fine-Tuning")
base_model.trainable = True
for layer in base_model.layers[:-30]:
    layer.trainable = False
model_densenet121.compile(optimizer=Adam(5e-5), loss='binary_crossentropy', metrics=['accuracy'])
model_densenet121.fit(
    train_generator, steps_per_epoch=steps_per_epoch, epochs=25,
    validation_data=val_generator, validation_steps=validation_steps,
    class_weight=class_weight_dict, callbacks=callbacks, verbose=1
)

# Phase 3: Final FT
print("\n🔧 PHASE 3: Final Fine-Tuning")
model_densenet121.compile(optimizer=Adam(1e-5), loss='binary_crossentropy', metrics=['accuracy'])
model_densenet121.fit(
    train_generator, steps_per_epoch=steps_per_epoch, epochs=15,
    validation_data=val_generator, validation_steps=validation_steps,
    class_weight=class_weight_dict, callbacks=callbacks, verbose=1
)

# =========================
# 7️⃣ ذخیره
# =========================
densenet121_path = os.path.join(DRIVE_MODEL_DIR, 'densenet121_patient_final.keras')
model_densenet121.save(densenet121_path)
print(f"\n💾 DenseNet121 saved: {densenet121_path}")

# =========================
# 8️⃣ ارزیابی DenseNet121
# =========================
print("\n📊 DenseNet121 Evaluation")
test_loss, test_acc = model_densenet121.evaluate(test_generator, verbose=0)
print(f"✅ DenseNet121 Test Accuracy: {test_acc*100:.2f}%")

y_pred = (model_densenet121.predict(test_generator) > 0.5).astype(int)
print("\nClassification Report:")
print(classification_report(test_df['label'], y_pred, target_names=["Benign", "Malignant"]))

print("\n✅ DenseNet121 DONE!")

