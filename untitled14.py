import os
import numpy as np
import pandas as pd
import tensorflow as tf

tf.keras.mixed_precision.set_global_policy('mixed_float16')

from sklearn.metrics import classification_report, confusion_matrix, accuracy_score
from tensorflow.keras.models import load_model
from tensorflow.keras.preprocessing.image import ImageDataGenerator

from google.colab import drive
drive.mount('/content/drive')

# =========================
# 1️⃣ بارگذاری تقسیم‌بندی
# =========================
SPLITS_PATH = "/content/drive/MyDrive/breakhis_ib_outputs/splits_patient_level.csv"
splits_df = pd.read_csv(SPLITS_PATH)

test_df = splits_df[splits_df['split'] == 'test'].reset_index(drop=True)
print(f"📊 Test: {len(test_df)}")

# =========================
# 2️⃣ بارگذاری مدل‌ها
# =========================
DRIVE_MODEL_DIR = "/content/drive/MyDrive/breakhis_models"

# DenseNet201 (از قبل آموزش دیده)
densenet201_path = os.path.join(DRIVE_MODEL_DIR, 'densenet201_patient_level_final.keras')
model_201 = load_model(densenet201_path)
print(f"✅ Loaded DenseNet201: {densenet201_path}")

# DenseNet121 (جدید)
densenet121_path = os.path.join(DRIVE_MODEL_DIR, 'densenet121_patient_final.keras')
model_121 = load_model(densenet121_path)
print(f"✅ Loaded DenseNet121: {densenet121_path}")

# =========================
# 3️⃣ بارگذاری تصاویر تست
# =========================
IMG_SIZE = 224

def load_image(img_path):
    img = tf.keras.utils.load_img(img_path, target_size=(IMG_SIZE, IMG_SIZE))
    return tf.keras.utils.img_to_array(img) / 255.0

print("\n📂 Loading test images...")
test_images = []
for p in test_df['filename']:
    test_images.append(load_image(p))
test_images = np.array(test_images)
print(f"✅ Loaded {len(test_images)} test images")

# =========================
# 4️⃣ پیش‌بینی با هر مدل
# =========================
print("\n🔮 Predicting with DenseNet201...")
pred_201 = model_201.predict(test_images, verbose=1)

print("\n🔮 Predicting with DenseNet121...")
pred_121 = model_121.predict(test_images, verbose=1)

# =========================
# 5️⃣ Ensemble (میانگین)
# =========================
ensemble_pred_prob = (pred_201 + pred_121) / 2.0
ensemble_pred = (ensemble_pred_prob > 0.5).astype(int)

# =========================
# 6️⃣ ارزیابی
# =========================
print("\n" + "="*60)
print("📊 ENSEMBLE RESULTS")
print("="*60)

# دقت هر مدل
acc_201 = accuracy_score(test_df['label'], (pred_201 > 0.5).astype(int))
acc_121 = accuracy_score(test_df['label'], (pred_121 > 0.5).astype(int))
acc_ensemble = accuracy_score(test_df['label'], ensemble_pred)

print(f"\n📊 DenseNet201 Accuracy:  {acc_201*100:.2f}%")
print(f"📊 DenseNet121 Accuracy:  {acc_121*100:.2f}%")
print(f"📊 Ensemble Accuracy:     {acc_ensemble*100:.2f}%")
print(f"📈 Improvement:           {(acc_ensemble - max(acc_201, acc_121))*100:.2f}%")

print("\n📋 Ensemble Classification Report:")
print(classification_report(test_df['label'], ensemble_pred, target_names=["Benign", "Malignant"]))

print("\n📊 Ensemble Confusion Matrix:")
print(confusion_matrix(test_df['label'], ensemble_pred))

# =========================
# 7️⃣ TTA روی Ensemble
# =========================
print("\n🎯 Running TTA on Ensemble...")

def predict_with_tta_ensemble(img, n_aug=5):
    # پیش‌بینی اصلی
    p201 = model_201.predict(np.expand_dims(img, axis=0), verbose=0)[0][0]
    p121 = model_121.predict(np.expand_dims(img, axis=0), verbose=0)[0][0]
    preds = [(p201 + p121) / 2.0]

    # پیش‌بینی با Augmentation
    for _ in range(n_aug):
        aug = img.copy()
        if np.random.random() > 0.5: aug = np.fliplr(aug)
        if np.random.random() > 0.5: aug = aug * np.random.uniform(0.7, 1.3)
        if np.random.random() > 0.5: aug = np.flipud(aug)

        p201_aug = model_201.predict(np.expand_dims(aug, axis=0), verbose=0)[0][0]
        p121_aug = model_121.predict(np.expand_dims(aug, axis=0), verbose=0)[0][0]
        preds.append((p201_aug + p121_aug) / 2.0)

    return np.mean(preds)

tta_preds = []
for i, img in enumerate(test_images):
    pred = predict_with_tta_ensemble(img)
    tta_preds.append(1 if pred > 0.5 else 0)
    if (i + 1) % 100 == 0:
        print(f"✅ Processed {i+1}/{len(test_images)}")

tta_acc = accuracy_score(test_df['label'], tta_preds)
print(f"\n✅ Ensemble + TTA Accuracy: {tta_acc*100:.2f}%")

print("\n📋 Ensemble + TTA Classification Report:")
print(classification_report(test_df['label'], tta_preds, target_names=["Benign", "Malignant"]))

print("\n📊 Ensemble + TTA Confusion Matrix:")
print(confusion_matrix(test_df['label'], tta_preds))

# =========================
# 8️⃣ خلاصه نهایی
# =========================
print("\n" + "="*60)
print("📊 FINAL SUMMARY")
print("="*60)
print(f"DenseNet201:         {acc_201*100:.2f}%")
print(f"DenseNet121:         {acc_121*100:.2f}%")
print(f"Ensemble:            {acc_ensemble*100:.2f}%")
print(f"Ensemble + TTA:      {tta_acc*100:.2f}%")